-- Provisional. Module 10.4 and scenario C7 are missing from the specification
-- entirely, and the contract entity appears in appendix 7 only as a link
-- target of permit and signature - it is never defined. These are open
-- questions P1, P2 and P5 to the customer.
--
-- The table exists because the application state machine already routes
-- through CONTRACT_DRAFT and permit will need a foreign key here. The column
-- set is deliberately the minimum that cannot be wrong, and WILL be revised
-- once P1 and P5 are answered: the parties, the subject, the term, the
-- payment schedule and the signature workflow are all still unknown.
CREATE TABLE app.contract (
    id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    application_id uuid NOT NULL REFERENCES app.application,
    number         text NOT NULL UNIQUE,
    status         text NOT NULL,
    signed_at      timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now(),
    created_by     uuid,
    updated_at     timestamptz NOT NULL DEFAULT now(),
    updated_by     uuid
);

ALTER TABLE app.contract
    -- Provisional list: the contract state machine is not specified anywhere.
    ADD CONSTRAINT contract_status_known CHECK (status IN ('DRAFT','SIGNED','TERMINATED')),
    ADD CONSTRAINT contract_signed_at_required CHECK (status <> 'SIGNED' OR signed_at IS NOT NULL);

CREATE INDEX contract_by_application ON app.contract (application_id);
