async def test_create_transaction_is_idempotent_by_paymes_id(db, client, pending_invoice):
    """Ruling 5 / design/04 §3.9: when Payme loses our answer it repeats the call
    verbatim. A second transaction row here would double-charge the applicant."""
    from sqlalchemy import func, select

    from app.modules.payments.models import ProviderTransaction

    tx_id = _tx_id("idempotent")
    params = {
        "id": tx_id,
        "time": 1_800_000_000_000,
        "amount": int(pending_invoice.amount * 100),
        "account": {"id": pending_invoice.number},
    }
    first = await _rpc(client, "CreateTransaction", params)
    second = await _rpc(client, "CreateTransaction", params)

    assert first.json()["result"]["transaction"] == second.json()["result"]["transaction"]
    assert first.json()["result"]["state"] == second.json()["result"]["state"] == 1
    assert first.json()["result"]["create_time"] == second.json()["result"]["create_time"]
    count = await db.scalar(
        select(func.count())
        .select_from(ProviderTransaction)
        .where(ProviderTransaction.provider == "payme", ProviderTransaction.external_id == tx_id)
    )
    assert count == 1


async def test_perform_marks_the_invoice_paid_writes_the_ledger_and_moves_the_application(
    db, client, pending_invoice
):
    """The single most important test in this stage: money arrives, and every
    consequence of that lands in one transaction.

    The brief's own version additionally asserted the application's card via
    `GET /api/v1/applications/{id}` through an unrelated `applicant_client`.
    `applications` ships no `router.py` on this branch (3.9a branch 1 only —
    verified, no route anywhere matches `applications/{`), so that call would
    404 regardless of this task's own correctness, and the 404's error
    envelope carries no `status` key either. The same invariant — the
    application reached PAID — is instead verified by reading the row back
    through `applications.service.get`, the public surface `payments.service`
    itself uses; `applicant_client` is dropped since nothing else in this
    test needs it.
    """
    from sqlalchemy import select

    from app.modules.applications import service as applications_service
    from app.modules.payments.models import Allocation

    params = {
        "id": _tx_id("perform"),
        "time": 1_800_000_000_000,
        "amount": int(pending_invoice.amount * 100),
        "account": {"id": pending_invoice.number},
    }
    await _rpc(client, "CreateTransaction", params)
    performed = await _rpc(client, "PerformTransaction", {"id": params["id"]})

    assert performed.json()["result"]["state"] == 2
    await db.refresh(pending_invoice)
    assert pending_invoice.status == "paid"
    assert pending_invoice.paid_at is not None

    entries = (
        await db.scalars(select(Allocation).where(Allocation.invoice_id == pending_invoice.id))
    ).all()
    assert {e.target for e in entries} == {"recipient", "budget"}
    assert sum(e.amount for e in entries) == pending_invoice.amount

    application = await applications_service.get(db, pending_invoice.application_id)
    assert application is not None
    await db.refresh(application)
    assert application.status == "PAID"


