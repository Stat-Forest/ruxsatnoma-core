"""The Payme JSON-RPC server (design/04 §3, plan `03.10a-payments-core` task 4).

Every test drives the route over HTTP (`client`, an anonymous Basic-Auth
client — `conftest.py`) rather than calling `payme.handle` directly: the
always-200 guarantee is a property of `payme_router.py`, not of `payme.py`
alone, and only an HTTP round-trip can prove it.

Two tests are restructured from the brief per ruling F — see each one's own
docstring for why. One assertion is restructured beyond ruling F, in
`test_perform_marks_the_invoice_paid_writes_the_ledger_and_moves_the_application`
— see its own docstring: `applications` ships no `router.py` on this branch
(verified: no `app/modules/applications/router.py`, no route anywhere
matching `applications/{`), so the brief's own
`GET /api/v1/applications/{id}` call would 404 regardless of this task's
correctness. The invariant it was checking (the application reached PAID)
is instead verified by reading the row back through
`applications.service.get`, the same public surface `payments.service`
itself uses.

Every Payme transaction `id` used below is generated by `_tx_id()`, never a
fixed literal (lesson: "The test DB is shared, persistent, and never empty"):
`client` is `_commit_pending_before_requests`-based and commits every request
for real, so a fixed literal like `"payme-tx-1"` would collide with the SAME
test's own row from a previous run (or a sibling worktree's), silently
changing what `CreateTransaction`'s idempotent-replay branch sees — a stale
row from hours or days ago reads as "past the 12h timeout" against the real
current time. Two count/total assertions are scoped to the row(s) this test
itself created for the identical reason: an unscoped `count(*)` over
`provider_transactions`/`allocations` counts every OTHER test's committed
rows too.
"""

import base64
import uuid
from datetime import timedelta
from decimal import Decimal


def _tx_id(label: str) -> str:
    """A Payme transaction id unique to this test run — see the module
    docstring for why a fixed literal is unsafe against the shared,
    persistent test DB."""
    return f"payme-{label}-{uuid.uuid4().hex[:12]}"


def _auth(key: str = "test-cashbox-key") -> dict[str, str]:
    token = base64.b64encode(f"Paycom:{key}".encode()).decode()
    return {"Authorization": f"Basic {token}"}


async def _rpc(client, method: str, params: dict, *, key: str = "test-cashbox-key"):
    return await client.post(
        "/api/v1/webhooks/payme",
        json={"jsonrpc": "2.0", "id": 1, "method": method, "params": params},
        headers=_auth(key),
    )


async def test_every_answer_is_http_200_including_the_errors(client, pending_invoice):
    """Ruling 2 / design/04 §3.1: Payme reads a non-200 as -32400, so even bad
    credentials and unknown methods must come back 200 with the error in the body."""
    bad_key = await _rpc(client, "CheckTransaction", {"id": "x"}, key="wrong")
    assert bad_key.status_code == 200
    assert bad_key.json()["error"]["code"] == -32504

    unknown = await _rpc(client, "NoSuchMethod", {})
    assert unknown.status_code == 200
    assert unknown.json()["error"]["code"] == -32601


async def test_a_malformed_body_never_500s(client):
    """Ruling B: malformed JSON and a non-object RPC envelope both answer 200
    with a Payme error code, never FastAPI's own `RequestValidationError` 422
    or an unhandled 500 — this route is never typed by a pydantic model."""
    garbage = await client.post("/api/v1/webhooks/payme", content=b"{not json", headers=_auth())
    assert garbage.status_code == 200
    assert garbage.json()["error"]["code"] == -32700

    not_an_object = await client.post("/api/v1/webhooks/payme", json=[1, 2, 3], headers=_auth())
    assert not_an_object.status_code == 200
    assert not_an_object.json()["error"]["code"] == -32600

    no_method = await client.post(
        "/api/v1/webhooks/payme", json={"jsonrpc": "2.0", "id": 1, "params": {}}, headers=_auth()
    )
    assert no_method.status_code == 200
    assert no_method.json()["error"]["code"] == -32600


